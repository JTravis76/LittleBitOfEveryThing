IF NOT EXISTS (
	SELECT 1 FROM INFORMATION_SCHEMA.TABLES
	WHERE TABLE_SCHEMA = 'dbo' AND TABLE_NAME = 'GrantorType'
)
BEGIN
	CREATE TABLE dbo.GrantorType (
		[Id] INT NOT NULL IDENTITY CONSTRAINT [PK_GrantorType_Id] PRIMARY KEY,
		[Name] VARCHAR(150) NULL,
        [Active] BIT NULL CONSTRAINT [DF_GrantorType_Active] DEFAULT 1
	);
END
GO